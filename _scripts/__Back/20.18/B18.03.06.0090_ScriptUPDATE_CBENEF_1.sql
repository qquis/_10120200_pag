	SET    fc_cbenef_cd = AA.pr_pag_fc_cbenef_cd
FROM ( 
			select	 	s.prsg_cdsubgrupo 
					,	s.fc_cbenef_cd 
					,	pr.pr_pag_fc_cbenef_cd
			from   		tbproduto pr 
			INNER join 	tbproduto_subgrupo s on s.prsg_cdsubgrupo = pr.prsg_cdsubgrupo 
			INNER JOIN  (
							select	 	s.prsg_cdsubgrupo 
									,	s.fc_cbenef_cd 
									,	count(distinct(pr.pr_pag_fc_cbenef_cd))
							from   		tbproduto pr 
							left join 	tbproduto_subgrupo s on s.prsg_cdsubgrupo = pr.prsg_cdsubgrupo 
							where		1 = 1
							and 		coalesce(pr.pr_pag_fc_cbenef_cd,'') != ''
							group by   s.prsg_cdsubgrupo 
									,	s.fc_cbenef_cd 
									,	pr.pr_pag_fc_cbenef_cd
							having count(distinct(pr.pr_pag_fc_cbenef_cd)) = 1
						) XX ON XX.prsg_cdsubgrupo = s.prsg_cdsubgrupo 
			where		1 = 1
			and 		coalesce(pr.pr_pag_fc_cbenef_cd,'') != ''
			group by   s.prsg_cdsubgrupo 
					,	s.fc_cbenef_cd 
					,	pr.pr_pag_fc_cbenef_cd
		) AA 
WHERE 	AA.prsg_cdsubgrupo = MM.prsg_cdsubgrupo
AND     COALESCE(MM.fc_cbenef_cd,'') = ''


